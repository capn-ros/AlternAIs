'use strict';
const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('api', {
  getState: () => ipcRenderer.invoke('state:get'),
  getVersion: () => ipcRenderer.invoke('app:version'),
  completeTutorial: () => ipcRenderer.invoke('tutorial:complete'),
  minimizeWindow: () => ipcRenderer.invoke('window:minimize'),
  toggleMaximizeWindow: () => ipcRenderer.invoke('window:toggle-maximize'),
  closeWindow: () => ipcRenderer.invoke('window:close'),
  add: (data) => ipcRenderer.invoke('account:add', data),
  update: (id, patch) => ipcRenderer.invoke('account:update', id, patch),
  select: (id) => ipcRenderer.invoke('account:select', id),
  toggleTheme: () => ipcRenderer.invoke('theme:toggle'),
  setSnippets: (list) => ipcRenderer.invoke('snippets:set', list),
  insertSnippet: (text) => ipcRenderer.invoke('snippet:insert', text),
  fsRoots: () => ipcRenderer.invoke('fs:roots'),
  fsList: (dir) => ipcRenderer.invoke('fs:list', dir),
  fsCopy: (paths, dest) => ipcRenderer.invoke('fs:copy', paths, dest),
  fsMove: (paths, dest) => ipcRenderer.invoke('fs:move', paths, dest),
  fsDelete: (paths) => ipcRenderer.invoke('fs:delete', paths),
  fsRename: (p, name) => ipcRenderer.invoke('fs:rename', p, name),
  fsMkdir: (dir, name) => ipcRenderer.invoke('fs:mkdir', dir, name),
  fsUnzip: (zip, dest) => ipcRenderer.invoke('fs:unzip', zip, dest),
  fsOpen: (p) => ipcRenderer.invoke('fs:open', p),
  fsReveal: (p) => ipcRenderer.invoke('fs:reveal', p),
  browserOpen: () => ipcRenderer.invoke('browser:open'),
  browserShow: (rect) => ipcRenderer.invoke('browser:show', rect),
  browserHide: () => ipcRenderer.invoke('browser:hide'),
  browserGo: (text) => ipcRenderer.invoke('browser:go', text),
  browserNav: (action) => ipcRenderer.invoke('browser:nav', action),
  browserDlGet: () => ipcRenderer.invoke('browser:dl-get'),
  browserDlSet: (mode) => ipcRenderer.invoke('browser:dl-set', mode),
  browserDlPick: () => ipcRenderer.invoke('browser:dl-pick'),
  onBrowserDownload: (cb) => ipcRenderer.on('browser-download', (_e, d) => cb(d)),
  browserExternal: () => ipcRenderer.invoke('browser:external'),
  onBrowserState: (cb) => ipcRenderer.on('browser-state', (_e, s) => cb(s)),
  setService: (svc) => ipcRenderer.invoke('service:set', svc),
  reload: (id) => ipcRenderer.invoke('account:reload', id),
  wipe: (id) => ipcRenderer.invoke('account:wipe', id),
  remove: (id) => ipcRenderer.invoke('account:remove', id),
  replyNow: (id, text) => ipcRenderer.invoke('account:reply', id, text),
  setLimit: (id, until, auto) => ipcRenderer.invoke('account:limit', id, until, auto),
  menu: (id) => ipcRenderer.invoke('account:menu', id),
  modal: (open) => ipcRenderer.invoke('ui:modal', !!open),
  drawer: (open) => ipcRenderer.invoke('ui:drawer', !!open),
  setSettings: (patch) => ipcRenderer.invoke('settings:set', patch),
  exportAccounts: () => ipcRenderer.invoke('data:export'),
  importAccounts: () => ipcRenderer.invoke('data:import'),
  openDownloads: () => ipcRenderer.invoke('app:downloads'),
  onState: (cb) => ipcRenderer.on('state', (_e, s) => cb(s)),
  onAction: (cb) => ipcRenderer.on('action', (_e, a) => cb(a)),
  onWindowState: (cb) => ipcRenderer.on('window-state', (_e, s) => cb(s)),
});
